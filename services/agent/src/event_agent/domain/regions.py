# 問いかけや関心条件で地域として受け付ける語。地方名と、よく使う都市名
KNOWN_LOCATIONS: tuple[str, ...] = (
    *REGION_PLACES,
    "大阪", "京都", "神戸", "兵庫", "奈良", "東京", "横浜", "名古屋", "札幌", "仙台",
    "広島", "福岡", "那覇",
    "オンライン",
)


def places_for(location: str) -> tuple[str, ...]:
    """地方名なら含まれる地名に広げる。それ以外（都市名など）はそのまま。"""
    return REGION_PLACES.get(location, (location,))


def in_locations(text: str, locations: list[str]) -> bool:
    """region / venue の文字列が、指定された地域のどれかに当たるか。"""
    # 「東京都」は「京都」を含む。部分一致で京都（関西）に当てないよう先に外す
    text = text.replace("東京都", "東京")
    return any(place and place in text for loc in locations for place in places_for(loc))
